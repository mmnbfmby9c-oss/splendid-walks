import os
import sys
from playwright.sync_api import sync_playwright
up=os.path.join(os.environ.get('GUIDE_PHOTOS',''),'Screenshot_2026-11-02_at_')  # your own screenshots of the guide's photo pages (not in this repo)
txt=open(sys.argv[3]).read()
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True,device_scale_factor=2)
    pg=ctx.new_page(); errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('file://'+sys.argv[1]); pg.wait_for_timeout(1500)
    pg.screenshot(path=sys.argv[2]+'/s1_first.png')
    print('dot visible before setup:', pg.locator('#guidedot').is_visible())
    pg.locator('#guidebtn').click(); pg.wait_for_timeout(300)
    pg.screenshot(path=sys.argv[2]+'/s2_sheet_empty.png')
    pg.locator('#bookbtn').click(); pg.locator('#bookpaste').fill(txt); pg.locator('#booksort').click(); pg.wait_for_timeout(600)
    pg.locator('#photobtn').click()
    for f in [x for x in ['1_21_18AM','1_21_35AM','1_21_50AM'] if os.path.exists(up+x+'.png')]:
        pg.set_input_files('#photofile', up+f+'.png'); pg.wait_for_timeout(2200); pg.locator('#photoadd').click(); pg.wait_for_timeout(700)
    pg.locator('#photocancel').click(); pg.wait_for_timeout(200)
    print('status:', pg.locator('#textstatus').inner_text(),'|',pg.locator('#photostatus').inner_text())
    pg.screenshot(path=sys.argv[2]+'/s3_sheet_done.png')
    pg.locator('#guideclose').click(); pg.wait_for_timeout(300)
    print('dot visible after setup:', pg.locator('#guidedot').is_visible())
    pg.locator('#tab-steps').click(); pg.wait_for_timeout(300)
    li=pg.locator('#steplist li').nth(12); li.scroll_into_view_if_needed(); li.click(); pg.wait_for_timeout(900)
    pg.evaluate('window.scrollTo(0,0)'); pg.wait_for_timeout(300)
    pg.screenshot(path=sys.argv[2]+'/s4_map13.png')
    pg.locator('#mapcard').scroll_into_view_if_needed(); pg.evaluate('window.scrollBy(0,-170)'); pg.wait_for_timeout(300)
    pg.screenshot(path=sys.argv[2]+'/s5_card13.png')
    pg.locator('#tab-steps').click(); pg.wait_for_timeout(300); pg.evaluate('window.scrollTo(0,0)')
    pg.screenshot(path=sys.argv[2]+'/s6_steps.png')
    pg.emulate_media(color_scheme='dark'); pg.locator('#tab-map').click(); pg.wait_for_timeout(500); pg.evaluate('window.scrollTo(0,0)')
    pg.screenshot(path=sys.argv[2]+'/s7_dark_map.png')
    pg.locator('#mapcard').scroll_into_view_if_needed(); pg.evaluate('window.scrollBy(0,-170)'); pg.wait_for_timeout(300)
    pg.screenshot(path=sys.argv[2]+'/s8_dark_card.png')
    ow=pg.evaluate('document.documentElement.scrollWidth'); print('phone scrollWidth',ow)
    ctx2=b.new_context(viewport={'width':1280,'height':860})
    d=ctx2.new_page(); d.goto('file://'+sys.argv[1]); d.wait_for_timeout(1200)
    d.screenshot(path=sys.argv[2]+'/s9_desktop.png')
    print('errors',errs); b.close()
